package postgres

import (
	"context"
	"errors"
	"fmt"

	"github.com/google/uuid"
	"github.com/jackc/pgx/v5"

	"technical-test-be-gdc-multi-sarana/internal/domain"
)

// TeamRepository implements service.TeamRepository.
type TeamRepository struct {
	db DB
}

// NewTeamRepository creates a TeamRepository.
func NewTeamRepository(db DB) *TeamRepository {
	return &TeamRepository{db: db}
}

const teamColumns = `id, name, invite_code, created_at`

func scanTeam(row pgx.Row) (*domain.Team, error) {
	var t domain.Team
	if err := row.Scan(&t.ID, &t.Name, &t.InviteCode, &t.CreatedAt); err != nil {
		if errors.Is(err, pgx.ErrNoRows) {
			return nil, domain.ErrNotFound
		}
		return nil, err
	}
	return &t, nil
}

// Create inserts a team. Its id and invite code are generated by the database.
func (r *TeamRepository) Create(ctx context.Context, name string) (*domain.Team, error) {
	q := `INSERT INTO teams (name) VALUES ($1) RETURNING ` + teamColumns
	t, err := scanTeam(conn(ctx, r.db).QueryRow(ctx, q, name))
	if err != nil {
		return nil, fmt.Errorf("insert team: %w", err)
	}
	return t, nil
}

// GetByID loads a team.
func (r *TeamRepository) GetByID(ctx context.Context, id uuid.UUID) (*domain.Team, error) {
	q := `SELECT ` + teamColumns + ` FROM teams WHERE id = $1`
	return scanTeam(conn(ctx, r.db).QueryRow(ctx, q, id))
}

// GetByInviteCode loads the team owning an invite code.
func (r *TeamRepository) GetByInviteCode(ctx context.Context, code string) (*domain.Team, error) {
	q := `SELECT ` + teamColumns + ` FROM teams WHERE invite_code = $1`
	return scanTeam(conn(ctx, r.db).QueryRow(ctx, q, code))
}
